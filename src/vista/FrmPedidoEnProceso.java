    public void actualizarFila(int fila, String avance, String estado){
        javax.swing.SwingUtilities.invokeLater(new Runnable(){
            @Override
            public void run(){
                javax.swing.table.DefaultTableModel modelo = (javax.swing.table.DefaultTableModel) tblProceso.getModel();
               modelo.setValueAt(avance, fila, 1);
               modelo.setValueAt(estado, fila, 2);
            }
        });
    }
    
    

