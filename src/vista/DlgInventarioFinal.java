    private void cargarTabla() {

        DefaultTableModel modelo = (DefaultTableModel) tblStockFinal.getModel();

        modelo.setRowCount(0);

        ArrayList<Producto> lista = inventario.getListaProductos();

        for (int i = 0; i < lista.size(); i++) {

            Producto producto = lista.get(i);

            int totalVendidos = producto.getExistenciaInicial()
                    - producto.getExistenciaActual();

            Object[] fila = {
                producto.getNombre(),
                totalVendidos,
                producto.getExistenciaActual()
            };

            modelo.addRow(fila);
        }
    }

